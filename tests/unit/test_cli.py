class TestCLIInit:
    """Tests for init command."""

    def test_init_run_creates_config(self, tmp_path):
        """init run creates a config file."""
        config_path = tmp_path / "test_config.yaml"
        result = runner.invoke(app, ["init", "run", "--path", str(config_path), "--name", "test-proj"])
        assert result.exit_code == 0
        assert config_path.exists()
        content = config_path.read_text()
        assert "test-proj" in content or "project" in content

    def test_init_without_subcommand_creates_config(self, tmp_path):
        """Plain `distill-align init` creates a config file (documented usage)."""
        config_path = tmp_path / "proj.yaml"
        result = runner.invoke(app, ["init", "--path", str(config_path), "--name", "my-proj"])
        assert result.exit_code == 0
        assert config_path.exists()

    def test_generated_config_is_parseable(self, tmp_path):
        """The config generated by init must be valid YAML."""
        from distill_align.core.config_file import load_config

        config_path = tmp_path / "proj.yaml"
        result = runner.invoke(app, ["init", "--path", str(config_path)])
        assert result.exit_code == 0

        config = load_config(config_path)  # raises on invalid YAML
        assert config.project.name == "my-dataset"


class TestCLIIngest:
    """Tests for ingest command."""

    def test_ingest_missing_file(self):
        """ingest with non-existent path shows error."""
        result = runner.invoke(app, ["ingest", "/nonexistent/path.md"])
        assert result.exit_code == 1
        assert "Error" in result.stdout or "exist" in result.stdout

    def test_ingest_markdown_file(self, tmp_path):
        """ingest works with a valid markdown file."""
        md_file = tmp_path / "test.md"
        md_file.write_text("# Hello\n\nWorld.", encoding="utf-8")
        output = tmp_path / "out.json"
        result = runner.invoke(
            app,
            [
                "ingest",
                str(md_file),
                "--output",
                str(output),
            ],
        )
        assert result.exit_code == 0
        assert output.exists()
        data = json.loads(output.read_text())
        assert len(data) > 0

    def test_ingest_empty_directory_errors(self, tmp_path):
        """ingest on a directory with no supported files fails loudly."""
        empty_dir = tmp_path / "empty"
        empty_dir.mkdir()
        output = tmp_path / "out.json"
        result = runner.invoke(app, ["ingest", str(empty_dir), "--output", str(output)])
        assert result.exit_code == 1
        assert "No chunks" in result.stdout
        assert not output.exists()


class TestCLIExport:
    """Tests for export command."""

    def test_export_missing_file(self):
        """export with non-existent path shows error."""
        result = runner.invoke(app, ["export", "/nonexistent/in.json"])
        assert result.exit_code == 1
        assert "Error" in result.stdout or "exist" in result.stdout

    def test_export_valid_conversations(self, tmp_path):
        """export works with valid conversations JSON."""
        from distill_align.core.schemas import ConversationSchema, SynthesizedTurn

        conv = ConversationSchema(
            id="test-cli-export-1",
            source_chunk_id="chunk-1",
            turns=[
                SynthesizedTurn(role="user", content="Hello"),
                SynthesizedTurn(role="assistant", content="Hi there!"),
            ],
        )
        input_file = tmp_path / "conversations.json"
        data = [conv.model_dump()]
        input_file.write_text(json.dumps(data, indent=2), encoding="utf-8")
        out_dir = tmp_path / "export"
        result = runner.invoke(
            app,
            [
                "export",
                str(input_file),
                "--output-dir",
                str(out_dir),
                "--format",
                "sharegpt",
                "--no-unsloth",
            ],
        )
        assert result.exit_code == 0
        assert out_dir.exists()
        files = list(out_dir.glob("*.json"))
        assert len(files) >= 1

    def test_export_preference_format(self, tmp_path):
        """export --format preference works end-to-end (documented in README)."""
        from distill_align.core.schemas import ConversationSchema, SynthesizedTurn

        conv = ConversationSchema(
            id="test-cli-export-pref",
            source_chunk_id="chunk-1",
            turns=[
                SynthesizedTurn(role="user", content="Hello"),
                SynthesizedTurn(role="assistant", content="Hi there!"),
            ],
        )
        input_file = tmp_path / "conversations.json"
        input_file.write_text(json.dumps([conv.model_dump()], indent=2), encoding="utf-8")
        out_dir = tmp_path / "pref"
        result = runner.invoke(
            app,
            [
                "export",
                str(input_file),
                "--output-dir",
                str(out_dir),
                "--format",
                "preference",
                "--no-unsloth",
            ],
        )
        assert result.exit_code == 0
        pref_file = out_dir / "dataset_preference.json"
        assert pref_file.exists()
        data = json.loads(pref_file.read_text())
        assert len(data) == 1
        assert "chosen" in data[0] and "rejected" in data[0]

    def test_export_unknown_format(self, tmp_path):
        """export rejects an unknown --format with a helpful message."""
        from distill_align.core.schemas import ConversationSchema, SynthesizedTurn

        conv = ConversationSchema(
            id="test-cli-export-unknown",
            source_chunk_id="chunk-1",
            turns=[SynthesizedTurn(role="user", content="Hello")],
        )
        input_file = tmp_path / "conversations.json"
        input_file.write_text(json.dumps([conv.model_dump()], indent=2), encoding="utf-8")
        out_dir = tmp_path / "unknown"
        result = runner.invoke(
            app,
            ["export", str(input_file), "--output-dir", str(out_dir), "--format", "bogus", "--no-unsloth"],
        )
        assert result.exit_code == 1
        assert "bogus" in result.stdout
        assert "sharegpt" in result.stdout or "alpaca" in result.stdout


