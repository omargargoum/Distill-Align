class TestCLISynthesize:
    """Tests for synthesize command validation."""

    @staticmethod
    def _chunks_file(tmp_path):
        chunk_file = tmp_path / "chunks.json"
        chunk_file.write_text(
            json.dumps(
                [
                    {
                        "id": "c1",
                        "content": "hello world",
                        "metadata": {"file_path": "a.md", "file_name": "a.md"},
                        "source": "a.md",
                        "index": 0,
                    }
                ]
            ),
            encoding="utf-8",
        )
        return chunk_file

    def test_synthesize_invalid_mode(self, tmp_path):
        """synthesize rejects an unknown --mode with a helpful message."""
        result = runner.invoke(app, ["synthesize", str(self._chunks_file(tmp_path)), "--mode", "bogus"])
        assert result.exit_code == 1
        assert "Invalid mode" in result.stdout
        assert "teach" in result.stdout and "explain" in result.stdout

    def test_synthesize_non_array_input(self, tmp_path):
        """synthesize rejects a JSON object (not an array) with a clear error."""
        bad_file = tmp_path / "bad.json"
        bad_file.write_text(json.dumps({"foo": "bar"}), encoding="utf-8")
        result = runner.invoke(app, ["synthesize", str(bad_file)])
        assert result.exit_code == 1
        assert "JSON array" in result.stdout


